const MIMETYPE: &str = "application/epub+zip";
const OCF: &str = "urn:oasis:names:tc:opendocument:xmlns:container";
const OPF: &str = "http://www.idpf.org/2007/opf";
const DC: &str = "http://purl.org/dc/elements/1.1/";
const NCX: &str = "http://www.daisy.org/z3986/2005/ncx/";

fn is_kanji(ch: char) -> bool {
    ch.script() == Script::Han
}

#[derive(Clone, Copy, Debug, Default)]
pub struct Options<'a> {
    /// Replace publisher ruby when Sudachi can read its entire base.
    pub override_existing: bool,
    /// Add a stylesheet rule that colors readings generated by this library.
    pub highlight_injected: bool,
    /// Enable highlighting with a CSS hex color such as `#2563eb`. The default color is `#c2410c`.
    pub highlight_color: Option<&'a str>,
    /// Assign a fresh primary Dublin Core identifier, keeping the previous identifier in metadata.
    pub new_identifier: bool,
    /// Set the primary Dublin Core identifier to this value, taking precedence over UUID generation.
    pub identifier: Option<&'a str>,
    /// Paths to UTF-8 wordlists with one word per line.
    ///
    /// Skip tokens whose written or dictionary form appears in any list.
    /// Publisher ruby containing a skipped token is preserved even when overriding.
    pub ignore_wordlists: &'a [PathBuf],
}

/// A reusable EPUB converter with a loaded Sudachi dictionary.
pub struct Furigana {
    dictionary: JapaneseDictionary,
}

impl Furigana {
    /// Load the V1 dictionary installed by [`download_dictionary`].
    pub fn from_default_dictionary() -> Result<Self> {
        Self::new(dictionary::default_dictionary_path()?)
    }

    /// Load a Sudachi V1 system dictionary from a local `.dic` file.
    pub fn new(dictionary_path: impl AsRef<Path>) -> Result<Self> {
        let path = dictionary_path.as_ref();
        let bytes = std::fs::read(path)
            .with_context(|| format!("reading Sudachi dictionary {}", path.display()))?;
        let storage = SudachiDicData::new(Storage::Owned(bytes));
        let dictionary = JapaneseDictionary::from_cfg_storage(&Config::new_embedded()?, storage)
            .with_context(|| format!("loading Sudachi V1 dictionary {}", path.display()))?;
        Ok(Self { dictionary })
    }

    /// Add hiragana ruby to the UTF-8 XHTML documents listed in an EPUB 3 package.
    ///
    /// Each XHTML text node is analyzed independently. Text without a usable
    /// dictionary reading is kept as-is. Identifier changes require an EPUB
    /// without encrypted or obfuscated resources.
    pub fn convert_epub(&self, epub: &[u8], options: Options<'_>) -> Result<Vec<u8>> {
        let highlight = xhtml::highlight_rule(options)?;
        let mut archive = ZipArchive::new(Cursor::new(epub)).context("opening EPUB")?;
        ensure!(
            read_entry(&mut archive, "mimetype")? == MIMETYPE,
            "invalid EPUB mimetype"
        );
        ensure!(
            !(options.new_identifier || options.identifier.is_some())
                || archive.index_for_name("META-INF/encryption.xml").is_none(),
            "cannot change the identifier of an EPUB with encrypted or obfuscated resources"
        );

        let container = read_entry(&mut archive, "META-INF/container.xml")?;
        let container = parse_xml(&container).context("parsing META-INF/container.xml")?;
        let packages: Vec<_> = container
            .descendants()
            .filter(|node| node.has_tag_name((OCF, "rootfile")))
            .filter_map(|node| node.attribute("full-path"))
            .collect();
        ensure!(
            !packages.is_empty(),
            "EPUB container lists no package document"
        );

        let ignored_words = read_ignored_words(options.ignore_wordlists)?;
        let tokenizer = StatelessTokenizer::new(&self.dictionary);
        let generated_identifier = (options.identifier.is_none() && options.new_identifier)
            .then(|| format!("urn:uuid:{}", Uuid::new_v4()));
        let identifier = options.identifier.or(generated_identifier.as_deref());
        let mut processed = HashSet::new();
        let mut replacements = HashMap::new();

        for full_path in packages {
            let path = resolve_href("", full_path)?;
            let source = read_entry(&mut archive, &path)?;
            let doc = parse_xml(&source).with_context(|| format!("parsing {path}"))?;
            let package = doc.root_element();
            ensure!(
                package.has_tag_name((OPF, "package")),
                "invalid EPUB package {path}"
            );
            ensure!(
                package.attribute("version") == Some("3.0"),
                "furigana conversion requires an EPUB 3 package: {path}"
            );
            let manifest = package
                .children()
                .find(|node| node.has_tag_name((OPF, "manifest")))
                .with_context(|| format!("missing manifest in {path}"))?;

            if let Some(identifier) = identifier
                && let Some(updated) = set_identifier(&source, package, identifier)
                    .with_context(|| format!("updating identifier in {path}"))?
            {
                replacements.insert(path.clone(), updated);
            }

            for item in manifest
                .children()
                .filter(|node| node.has_tag_name((OPF, "item")))
            {
                let media_type = item.attribute("media-type");
                let ncx_identifier =
                    identifier.filter(|_| media_type == Some("application/x-dtbncx+xml"));
                if media_type != Some("application/xhtml+xml") && ncx_identifier.is_none() {
                    continue;
                }
                let href = item
                    .attribute("href")
                    .context("manifest item has no href")?;
                let entry = resolve_href(&path, href)?;
                if !processed.insert(entry.clone()) {
                    continue;
                }
                let source = read_entry(&mut archive, &entry)?;
                let updated = match ncx_identifier {
                    Some(identifier) => update_ncx(&source, identifier),
                    None => xhtml::annotate(
                        &source,
                        &tokenizer,
                        &ignored_words,
                        options.override_existing,
                        highlight.as_deref(),
                    ),
                }
                .with_context(|| format!("processing {entry}"))?;
                if let Some(updated) = updated {
                    replacements.insert(entry, updated);
                }
            }
        }

        if replacements.is_empty() {
            return Ok(epub.to_vec());
        }

        let mut output = ZipWriter::new(Cursor::new(Vec::new()));
        output.set_raw_comment(archive.comment().into())?;
        let stored = SimpleFileOptions::default()
            .last_modified_time(zip::DateTime::DEFAULT)
            .compression_method(CompressionMethod::Stored);
        output.start_file("mimetype", stored)?;
        output.write_all(MIMETYPE.as_bytes())?;

        for index in 0..archive.len() {
            let entry = archive.by_index_raw(index)?;
            let name = entry.name()?;
            if name == "mimetype" {
                continue;
            }
            if let Some(content) = replacements.get(name.as_ref()) {
                output.start_file(name, stored.compression_method(entry.compression()))?;
                output.write_all(content.as_bytes())?;
            } else {
                output.raw_copy_file(entry)?;
            }
        }

        Ok(output.finish()?.into_inner())
    }
}

fn read_ignored_words(paths: &[PathBuf]) -> Result<HashSet<String>> {
    let mut words = HashSet::new();
    for path in paths {
        let list = std::fs::read_to_string(path)
            .with_context(|| format!("reading wordlist {}", path.display()))?;
        words.extend(
            list.trim_start_matches('\u{feff}')
                .lines()
                .map(str::trim)
                .filter(|word| !word.is_empty())
                .map(str::to_owned),
        );
    }
    Ok(words)
}

fn read_entry(archive: &mut ZipArchive<Cursor<&[u8]>>, path: &str) -> Result<String> {
    let mut source = String::new();
    archive
        .by_name(path)
        .with_context(|| format!("opening {path} in EPUB"))?
        .read_to_string(&mut source)
        .with_context(|| format!("reading UTF-8 from {path}"))?;
    Ok(source)
}

fn parse_xml(source: &str) -> Result<Document<'_>> {
    // XHTML can carry a <!DOCTYPE html> declaration.
    Ok(Document::parse_with_options(
        source,
        ParsingOptions {
            allow_dtd: true,
            ..ParsingOptions::default()
        },
    )?)
}

fn resolve_href(package: &str, href: &str) -> Result<String> {
    let path = href.split(['?', '#']).next().unwrap_or_default();
    ensure!(
        !path.is_empty()
            && !path.starts_with("//")
            && !path.split('/').next().unwrap_or_default().contains(':'),
        "expected a local EPUB manifest href, got {href:?}"
    );
    let mut parts: Vec<_> = if path.starts_with('/') {
        Vec::new()
    } else {
        package
            .rsplit_once('/')
            .map(|(dir, _)| dir.split('/').map(str::to_owned).collect())
            .unwrap_or_default()
    };
    for part in path.split('/') {
        let part = percent_decode_str(part).decode_utf8()?;
        match part.as_ref() {
            "" | "." => {}
            ".." => ensure!(
                parts.pop().is_some(),
                "EPUB href leaves the archive root: {href}"
            ),
            name => {
                ensure!(!name.contains('/'), "invalid EPUB href: {href}");
                parts.push(name.to_owned());
            }
        }
    }
    Ok(parts.join("/"))
}

fn set_identifier(source: &str, package: Node<'_, '_>, identifier: &str) -> Result<Option<String>> {
    let metadata = package
        .children()
        .find(|node| node.has_tag_name((OPF, "metadata")))
        .context("missing package metadata")?;
    let primary = package
        .attribute_node("unique-identifier")
        .context("missing unique-identifier")?;
    let escaped_identifier = escape_identifier(identifier)?;
    let current = metadata.children().find(|node| {
        node.has_tag_name((DC, "identifier")) && node.attribute("id") == Some(primary.value())
    });
    if current.and_then(|node| node.text()) == Some(identifier) {
        return Ok(None);
    }

    // Keep identifiers such as ISBNs, including any metadata refining them.
    let mut id = String::from("furigana4epub-id");
    while package
        .descendants()
        .any(|node| node.attribute("id") == Some(id.as_str()))
    {
        id.push('_');
    }
    let start = closing_tag(source, metadata)?.start;
    Ok(Some(apply_edits(
        source,
        vec![
            (primary.range_value(), id.clone()),
            (
                start..start,
                format!(
                    "<dc:identifier xmlns:dc=\"{DC}\" id=\"{id}\">{escaped_identifier}</dc:identifier>"
                ),
            ),
        ],
    )?))
}

fn update_ncx(source: &str, identifier: &str) -> Result<Option<String>> {
    let doc = parse_xml(source)?;
    let ranges: Vec<_> = doc
        .descendants()
        .filter(|node| {
            node.has_tag_name((NCX, "meta")) && node.attribute("name") == Some("dtb:uid")
        })
        .filter_map(|node| node.attribute_node("content"))
        .filter(|attribute| attribute.value() != identifier)
        .map(|attribute| attribute.range_value())
        .collect();
    if ranges.is_empty() {
        return Ok(None);
    }
    let escaped = escape_identifier(identifier)?;
    let edits = ranges
        .into_iter()
        .map(|range| (range, escaped.clone()))
        .collect();
    Ok(Some(apply_edits(source, edits)?))
}

fn escape_identifier(identifier: &str) -> Result<String> {
    ensure!(
        !identifier.trim().is_empty(),
        "expected a non-empty EPUB identifier"
    );
    let mut escaped = String::with_capacity(identifier.len());
    for character in identifier.chars() {
        match character {
            '&' => escaped.push_str("&amp;"),
            '<' => escaped.push_str("&lt;"),
            '>' => escaped.push_str("&gt;"),
            '"' => escaped.push_str("&quot;"),
            '\'' => escaped.push_str("&apos;"),
            '\t' => escaped.push_str("&#9;"),
            '\n' => escaped.push_str("&#10;"),
            '\r' => escaped.push_str("&#13;"),
            ' '..='\u{D7FF}' | '\u{E000}'..='\u{FFFD}' | '\u{10000}'..='\u{10FFFF}' => {
                escaped.push(character);
            }
            _ => bail!("EPUB identifier contains a character forbidden in XML"),
        }
    }
    Ok(escaped)
}

type Edit = (Range<usize>, String);

fn closing_tag(source: &str, node: Node<'_, '_>) -> Result<Range<usize>> {
    let range = node.range();
    let start = source[range.clone()]
        .rfind("</")
        .context("missing closing tag")?;
    Ok(range.start + start..range.end)
}

fn apply_edits(source: &str, mut edits: Vec<Edit>) -> Result<String> {
    edits.sort_by_key(|(range, _)| range.start);
    let mut result = String::with_capacity(source.len());
    let mut previous_end = 0;
    for (range, replacement) in edits {
        ensure!(range.start >= previous_end, "overlapping XML edits");
        result.push_str(&source[previous_end..range.start]);
        result.push_str(&replacement);
        previous_end = range.end;
    }
    result.push_str(&source[previous_end..]);
    Ok(result)
}
