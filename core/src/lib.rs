//! Add Sudachi readings to EPUB XHTML content.
//!
//! Install the default dictionary with [`download_dictionary`].
//!
//! ```no_run
//! use furigana4epub_core::{Furigana, Options};
//!
//! # fn main() -> anyhow::Result<()> {
//! let converter = Furigana::from_default_dictionary()?;
//! let epub = std::fs::read("input.epub")?;
//! let output = converter.convert_epub(&epub, Options::default())?;
//! std::fs::write("output.epub", output)?;
//! # Ok(())
//! # }
//! ```

